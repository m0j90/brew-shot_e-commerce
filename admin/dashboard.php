        $total_revenue += floatval($order['subtotal'] ?? 0);
        if (strtolower($order['status'] ?? '') === 'pending') {
            $pending_orders++;
        } 
    }

    $total_subadmins = count(array_filter($admins, function($admin) {
        $role = strtolower($admin['role'] ?? $admin['position'] ?? '');
