        $file = __DIR__ . '/../data/admins.json';
        $admins = file_exists($file) ? json_decode(file_get_contents($file), true) : [];

        $admin_found = false;
        $logged_in_admin = null;

        if (is_array($admins)) {
            foreach ($admins as $admin) {
                if ($admin['email'] === $email && $admin['position'] === $position) {
                    if (password_verify($password, $admin['password_hash'])) {
                        $admin_found = true;
                        $logged_in_admin = $admin;
                        break;
                    }
                }
            }
        }

        if ($admin_found) {
            $_SESSION['admin'] = $logged_in_admin;
            header('Location: dashboard.php');
            exit();
        } else {
            header('Location: index.php?invalid=1');
            exit();
        }
    } else {
        if (!isset($_SESSION['admin'])) {
            header('Location: index.php');
            exit();
        }
    }

